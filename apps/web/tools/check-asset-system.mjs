  await page.getByRole('tab', { name: /全部形态/ }).click()
  await page.screenshot({ path: `${out}/four-forms-light.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: `${out}/four-forms-mobile.png`, fullPage: true })
