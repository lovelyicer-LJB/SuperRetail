  await page.getByRole('button', { name: '清空连线' }).click()
  await expect(page.locator('[data-asset-node]')).toHaveCount(7)
  await expect(page.getByText('待补全制作依赖', { exact: true })).toBeVisible()
  const port = (node, side, name) => page.locator(`[data-node="${node}"][data-side="${side}"][data-port="${name}"]`)
  const link = async (source, output, target, input) => { await port(source, 'output', output).click(); await port(target, 'input', input).click() }
  await link('anjihai-chili', 'supply', 'recipe', 'tea')
  await expect(page.getByRole('status')).toContainText('端口不匹配')
  await expect(page.locator('.asset-wire-hit')).toHaveCount(0)
  await link('anjihai-chili', 'supply', 'recipe', 'chili')
  await link('xihu-longjing', 'supply', 'recipe', 'tea')
  await link('jinhua-ham', 'supply', 'recipe', 'ham')
  await link('recipe', 'recipe', 'food', 'recipe')
  // Drag-to-connect and click-to-connect share the same validation.
  const start = await port('chef', 'output', 'chef').boundingBox(), end = await port('food', 'input', 'chef').boundingBox()
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 8 })
  await page.mouse.up()
  await expect(page.getByText('制作依赖已就绪', { exact: true })).toBeVisible()
  await link('food', 'sell', 'buyer', 'buy')
  await expect(page.locator('[data-asset-node]')).toHaveCount(8)
