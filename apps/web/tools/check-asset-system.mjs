  await expect(page.locator('.asset-wire-hit')).toHaveCount(8)
  await expect(port('recipe', 'input', 'buy')).toHaveCount(0)
  await page.getByRole('checkbox', { name: '配方完全持有' }).uncheck()
  await link(revenue, 'license', 'recipe', 'buy')
  // Removing a sale removes its derived node and every outgoing allocation.
  await page.getByRole('button', { name: '选择连线 辣龙腿 到 餐厅采购', exact: true }).focus()
  await page.keyboard.press('Enter')
